const DICTS: Record<AdminLang, Record<string, string>> = { zh, en };

export function translateAdmin(
  lang: AdminLang,
  key: string,
  params?: Record<string, string | number>
): string {
  let s = DICTS[lang][key] ?? DICTS.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}

export interface AdminI18nState {
  lang: AdminLang;
  setLang: (l: AdminLang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

// default context; real provider mounted in main.tsx
export const AdminI18nContext = createContext<AdminI18nState>({
  lang: "zh",
  setLang: () => {},
  t: (k) => translateAdmin("zh", k),
});

export function useAdminI18n(): AdminI18nState {
  return useContext(AdminI18nContext);
}
