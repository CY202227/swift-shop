// Admin backoffice i18n: zh/en dictionaries + context + localStorage persistence.
import { createContext, useContext } from "react";

export type AdminLang = "zh" | "en";

const STORAGE_KEY = "admin_lang";

export function detectLang(): AdminLang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    // storage unavailable
  }
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function saveLang(l: AdminLang) {
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    // ignore
  }
}

